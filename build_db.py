"""Builds sql/churn.db (SQLite) from the CSVs and runs all SQL files -> docs/sql_results.md"""
import sqlite3, pandas as pd, re, os
if os.path.exists("sql/churn.db"): os.remove("sql/churn.db")
con=sqlite3.connect("sql/churn.db"); con.executescript(open("sql/01_schema.sql").read())
cl=pd.read_csv("data/telecom_churn_clean.csv")
cols=[r[1] for r in con.execute("PRAGMA table_info(customers)")]; cl[cols].to_sql("customers",con,if_exists="append",index=False)
sc=pd.read_csv("data/telecom_churn_scored.csv").fillna({"playbook":""})[["customer_id","churn_probability","risk_tier","playbook"]]; sc.to_sql("churn_scores",con,if_exists="append",index=False)
out=["# SQL query results (auto-generated by build_db.py)\n"]
for f in ["sql/02_data_quality_checks.sql","sql/03_churn_analysis.sql"]:
    for m in re.finditer(r"-- @(\w+) ([^\n]*)\n(.*?)(?=\n-- @|\Z)",open(f).read(),re.S):
        n,t,q=m.groups(); r=pd.read_sql_query(q.strip(),con); out.append(f"\n## {n} - {t}\n\n"+r.to_markdown(index=False,floatfmt=".4g")+"\n"); print("OK",n,r.shape)
open("docs/sql_results.md","w").write("\n".join(out))
